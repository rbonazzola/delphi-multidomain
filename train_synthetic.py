REAL_TOKENS_ROOT = DELPHI_DIR / "data" / "transforms" / "tokens"
REAL_FOLDS_DIR = DELPHI_DIR / "data" / "transforms" / "subject_lists"
AUC_BLOCK_SIZE = 128  # evaluate_aucs needs a fixed T across batches (see train.py)

SYNTHETIC_DOMAINS = ("sex", "lifestyle", "diseases", "death")


def build_domain_config(tokens_dir: Path) -> dict:
    """Domain config for the 4 domains generate_synthetic_subjects.py writes.
    Mirrors config/domain_config_default.yaml's settings for these domains,
    but with `path` pointing directly (as an absolute path) at tokens_dir --
    bypassing the usual root/tokens/<path> YAML resolution, since this
    synthetic folder isn't necessarily under data/transforms/tokens/.
    """
    return {
        "sex": DomainConfig(
            projector="embed", path=str(tokens_dir / "sex"), at_birth=True,
        ),
        "lifestyle": DomainConfig(
            projector="embed", path=str(tokens_dir / "lifestyle"),
            dropout_mode="token", dropout_rate=0.1,
            age_jitter=True, age_jitter_min=-7300, age_jitter_max=14610,
        ),
        "diseases": DomainConfig(
            projector="embed", path=str(tokens_dir / "diseases"),
            predict=True, no_repeat=True, dropout_mode="token", dropout_rate=0.1,
        ),
        "death": DomainConfig(
            projector="embed", path=str(tokens_dir / "death"), predict=True,
        ),
        "padding": DomainConfig(projector="embed"),
        "no_event": DomainConfig(projector="embed", predict=False),
    }


def split_subjects(tokens_dir: Path, val_frac: float, test_frac: float, seed: int, n_subjects_debug=None):
    """Fresh random train/val/test split over the synthetic subject_ids.

    Every synthetic subject has exactly one 'sex' token (it's at_birth), so
    that domain's tokens.csv is the cheapest place to read the full
    subject_id list from.

    n_subjects_debug: if given, subsample the pool down to this many subjects
    (from the already-generated tokens_dir) before splitting -- for a quick
    sanity run over a large pre-generated cohort, without regenerating
    anything smaller.
    """
    subject_ids = pd.read_csv(tokens_dir / "sex" / "tokens.csv")["subject_id"].unique()
    rng = np.random.default_rng(seed)
    subject_ids = rng.permutation(subject_ids)
    if n_subjects_debug is not None:
        subject_ids = subject_ids[:n_subjects_debug]
    n = len(subject_ids)
    n_val = int(n * val_frac)
    n_test = int(n * test_frac)
    val_ids = subject_ids[:n_val].tolist()
    test_ids = subject_ids[n_val:n_val + n_test].tolist()
    train_ids = subject_ids[n_val + n_test:].tolist()
    return train_ids, val_ids, test_ids


