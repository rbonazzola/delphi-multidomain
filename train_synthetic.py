def get_dataloaders(domain_cfg, model, tokens_dir, args):
    train_ids, val_ids, test_ids = split_subjects(
        tokens_dir, args.val_frac, args.test_frac, args.seed, n_subjects_debug=args.n_subjects_debug
    )
    logging.info("Synthetic split: %d train / %d val / %d test", len(train_ids), len(val_ids), len(test_ids))

    root = str(DELPHI_DIR / "data" / "transforms")  # inert here: every domain path above is absolute

    dataset_kwargs = dict(
        root=root, domains_cfg=domain_cfg, domain_to_int=model.domain_to_int,
        block_size=args.block_size, required_domains=["sex"],
        no_event_token_rate=args.no_event_token_rate,
        no_event_insertion_mode=args.no_event_token_insertion_mode,
        age_domains=["diseases", "death"],
    )
    train_dataset = DelphiDataset(subjects=train_ids, **dataset_kwargs)
    valid_dataset = DelphiDataset(subjects=val_ids, **dataset_kwargs)
    test_dataset = DelphiDataset(subjects=test_ids, **dataset_kwargs)

    age_sampler = AgeSampler(
        insertion_mode=args.no_event_token_insertion_mode,
        token_rate=args.no_event_token_rate,
        seed=args.seed,
    )

    domain_dropout = {
        model.domain_to_int[dname]: (cfg.dropout_mode, cfg.dropout_rate, cfg.token_dropout_rate, cfg.parent or dname)
        for dname, cfg in domain_cfg.items()
        if cfg.dropout_mode is not None and cfg.dropout_rate > 0
    }
    age_jitter = {
        model.domain_to_int[dname]: (cfg.age_jitter_min, cfg.age_jitter_max)
        for dname, cfg in domain_cfg.items()
        if cfg.age_jitter and dname in model.domain_to_int
    }

    collate_kwargs = dict(
        age_sampler=age_sampler, block_size=args.block_size, domain_to_int=model.domain_to_int,
        domain_offsets=model.domain_offsets, padding_domain_id=model.domain_to_int["padding"],
        no_event_domain_id=model.domain_to_int["no_event"], continuous_domains={},
        domain_dropout=domain_dropout,
    )
    train_collate = DelphiCollateFn(**collate_kwargs, age_jitter=age_jitter, training=True)
    eval_collate = DelphiCollateFn(**collate_kwargs, training=False)

    train_kwargs = dict(batch_size=args.batch_size, num_workers=args.num_workers, pin_memory=True)
    eval_kwargs = dict(batch_size=args.eval_batch_size, num_workers=args.num_workers, pin_memory=True)

    train_loader = FlexibleDataLoader(train_dataset, shuffle=True, collate_fn=train_collate, **train_kwargs)
    valid_loader = FlexibleDataLoader(valid_dataset, shuffle=False, collate_fn=eval_collate, **eval_kwargs)
    test_loader = FlexibleDataLoader(test_dataset, shuffle=False, collate_fn=eval_collate, **eval_kwargs)

    return DataModule(train_loader, valid_loader, test_loader)


def build_real_eval_loader(model, real_test_fold, eval_batch_size, num_workers):
    """Real-data test DataLoader for evaluate_aucs, over the same 4 domains
    the synthetic-trained model has embeddings for. Vocab is identical to
    the synthetic training data (see module docstring), so this model can
    be run directly on it without any remapping.
    """
    real_domain_cfg = build_domain_config(REAL_TOKENS_ROOT)
    _, _, real_test_ids = get_data_partitions(str(REAL_FOLDS_DIR), fold=real_test_fold)

    real_test_dataset = DelphiDataset(
        root=str(DELPHI_DIR / "data" / "transforms"), domains_cfg=real_domain_cfg,
        domain_to_int=model.domain_to_int, block_size=AUC_BLOCK_SIZE,
        subjects=real_test_ids, required_domains=["sex"],
        age_domains=["diseases", "death"],
    )
    eval_collate = DelphiCollateFn(
        age_sampler=AgeSampler(insertion_mode="random", token_rate=2.0, seed=0),
        block_size=AUC_BLOCK_SIZE, domain_to_int=model.domain_to_int,
        domain_offsets=model.domain_offsets, padding_domain_id=model.domain_to_int["padding"],
        no_event_domain_id=model.domain_to_int["no_event"], continuous_domains={},
        training=False,
    )
    from torch.utils.data import DataLoader
    return DataLoader(
        real_test_dataset, batch_size=eval_batch_size, shuffle=False,
        num_workers=num_workers, pin_memory=True, collate_fn=eval_collate,
    )


def main():
    args = get_cli_args()
    setup_mlflow()

    tokens_dir = args.tokens_dir.resolve()
    for d in SYNTHETIC_DOMAINS:
        tokens_csv = tokens_dir / d / "tokens.csv"
        if not tokens_csv.exists():
            raise FileNotFoundError(
                f"{tokens_csv} not found -- run generate_synthetic_subjects.py "
                f"with --output_dir {tokens_dir} first"
            )

    domain_cfg = build_domain_config(tokens_dir)

    delphi_config = DelphiConfig(
        n_layer=args.n_layer, n_head=args.n_head, n_embd=args.n_embd,
        domains=domain_cfg, attention_scheme=args.attention_scheme,
        token_dropout=args.token_dropout, block_size=args.block_size,
        no_event_token_rate=args.no_event_token_rate,
        no_event_token_insertion_mode=args.no_event_token_insertion_mode,
        seed=args.seed,
    )

    if args.dry_run:
        print(delphi_config)
        sys.exit(0)

    model = Delphi(delphi_config).to(DEVICE)
    model = _compile_model(model, disable=args.no_compile)

    dataloaders = get_dataloaders(domain_cfg, model, tokens_dir, args)

    optim_config = OptimConfig(
        learning_rate=args.lr,
        min_lr=args.min_lr if args.min_lr is not None else args.lr / 10,
        weight_decay=args.weight_decay,
        grad_clip=args.grad_clip,
        schedule=args.schedule,
        warmup_iters=args.warmup_iters,
        lr_decay_iters=args.lr_decay_iters,
    )
    optimizer, scheduler = configure_optimizers(model=model, cfg=optim_config, device_type=DEVICE)

    logger = MLFlowLogger(experiment_name=args.experiment_name, run_name=args.run_name)
    logger.log_run_metadata(cwd=DELPHI_DIR)

    n_params = sum(p.numel() for p in model.parameters())
    logged_params = {
        "tokens_dir": str(tokens_dir),
        "synthetic": True,
        "n_subjects_debug": args.n_subjects_debug,
        "val_frac": args.val_frac,
        "test_frac": args.test_frac,
        "batch_size": args.batch_size,
        "learning_rate": args.lr,
        "seed": args.seed,
        "optim_config": optim_config,
        "max_epochs": args.max_epochs,
        "min_epochs": args.min_epochs,
        "patience": args.patience,
        "n_params": n_params,
    }

    dataloaders.log_info()
    logged_params["n_train"] = dataloaders.n_train
    logged_params["n_val"] = dataloaders.n_val
    logged_params["n_test"] = dataloaders.n_test

    trainer = Trainer(
        model, dataloaders,
        optimizer, scheduler,
        log_loss_per_disease=args.log_loss_per_disease,
        baseline_incidence_path=args.baseline_incidence_path,
        checkpoint_every=args.checkpoint_every,
        logger=logger,
        mlflow_params=logged_params,
        use_tqdm=args.no_rich,
        use_amp=args.use_amp,
        use_rich=not args.no_rich,
        optim_config=optim_config,
    )

    trainer.train(max_epochs=args.max_epochs, min_epochs=args.min_epochs, patience=args.patience)

    if args.compute_real_aucs:
        model.eval()
        real_test_loader = build_real_eval_loader(
            model, args.real_test_fold, args.eval_batch_size, args.num_workers
        )
        auc_df = evaluate_aucs(
            model, real_test_loader, block_size=AUC_BLOCK_SIZE,
            run_id=logger.active_run.info.run_id, n_jobs=8, logger=logger,
            output_file="aucs_real.csv",
        )
        logging.info("Real-data AUCs (model trained on synthetic data):\n%s", auc_df)


if __name__ == "__main__":
    main()
