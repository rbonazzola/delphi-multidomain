"""
Train a fresh Delphi model on synthetic subjects generated by
generate_synthetic_subjects.py, standalone from train.py.

Only the domains that script actually writes are available: sex, lifestyle,
diseases, death (no drugs/hla_alleles/genetic_pcs/rare_variants -- the model
never generates those on its own, see generate_synthetic_subjects.py's
docstring). Splits are a fresh random train/val/test partition over whatever
subject_ids are found under --tokens_dir: these synthetic IDs live outside
the real UKB cohort's fold files (data/transforms/subject_lists/), so
train.py's CV/fold machinery (utils.cv_utils.get_data_partitions) does not
apply to them and is intentionally not reused here.

Usage:
    python train_synthetic.py \\
        --tokens_dir data/transforms/tokens/synthetic \\
        --experiment_name synthetic-delphi \\
        --max_epochs 100 \\
        --compute_real_aucs

--compute_real_aucs evaluates the trained model's AUCs on REAL subjects
(a real UKB test fold, via utils.cv_utils.get_data_partitions), not on
synthetic ones -- the point of training on synthetic data is to see whether
it generalizes to the real disease distribution, so evaluating on more
synthetic data wouldn't answer that. This works because
generate_synthetic_subjects.py copies each domain's real tokenizer.yaml
verbatim into the synthetic output, so token_ids for sex/lifestyle/diseases/
death are identical between the synthetic training data and the real
evaluation data -- no vocab mismatch.
"""
